// Calendar module test. Runs on its own against a throwaway copy of the data:
//
//   node --test server/          (or: node server/slots.test.mjs)
//
// With BASE=http://localhost:4752 it runs against that server instead.
//
// It regenerates 2026-11-01 to 2027-03-31, checks the generation rules, the fit
// table and the dark-day refusal, and removes every piece and slot it creates.
// With ROUNDTRIP=<path to the Studio data folder> it also writes
// data/import-calendar.json from ../Marketing/POSTING/calendar.csv, imports it,
// and checks that the exported CSV is byte-identical to the original.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startScratch } from './_scratch.mjs';

const scratch = process.env.BASE ? null : await startScratch({ label: 'studio-slots' });
const BASE = process.env.BASE || scratch.base;
const USER = 'tools@vspindia.com';
let failed = 0; let passed = 0;

async function call(method, url, body) {
  const res = await fetch(`${BASE}${url}`, {
    method, headers: { 'content-type': 'application/json', 'X-Studio-User': USER }, body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await res.text();
  let data; try { data = JSON.parse(text); } catch { data = text; }
  return { status: res.status, data };
}
function check(name, ok, extra) {
  if (ok) { passed += 1; console.log(`  ok    ${name}`); } else { failed += 1; console.log(`  FAIL  ${name}${extra ? `: ${extra}` : ''}`); }
}

const from = '2026-11-01'; const to = '2027-03-31';
console.log(`Calendar tests against ${BASE}`);

const reg = await call('POST', '/api/slots/regenerate', { from, to });
check('regenerate returns 200', reg.status === 200, JSON.stringify(reg.data));
console.log('  summary', JSON.stringify(reg.data));
const reg2 = await call('POST', '/api/slots/regenerate', { from, to });
check('regenerate is idempotent (nothing created or removed the second time)', reg2.data.created === 0 && reg2.data.removed === 0 && reg2.data.total === reg.data.total, JSON.stringify(reg2.data));

const cal = await call('GET', `/api/calendar?from=${from}&to=${to}`);
check('calendar range returns 200', cal.status === 200);
const slots = cal.data.slots;
const on = (d) => slots.filter((s) => s.date === d);
const has = (d, kind, account) => on(d).some((s) => s.kind === kind && (!account || s.accountId === account));

check('no slot at all on 2026-11-09 (Govardhan Puja, dark): the series starts on 16 November', on('2026-11-09').length === 0, JSON.stringify(on('2026-11-09').map((s) => s.kind)));
check('2026-11-03 has a LinkedIn slot', has('2026-11-03', 'li', 'p-li'));
check('2026-11-05 has no LinkedIn slot (one a week before 16 Nov)', !has('2026-11-05', 'li'));
check('2026-11-12 carries the week\'s LinkedIn slot (Tuesday 10 Nov is dark)', has('2026-11-12', 'li', 'p-li'));
check('2026-11-25 has a li-carousel slot', has('2026-11-25', 'li-carousel', 'p-li'));
check('2026-11-26 has no LinkedIn slot (carousel week replaces Thursday)', !has('2026-11-26', 'li'));
check('2026-12-02 (Wednesday, non-carousel week) has no li-carousel', !has('2026-12-02', 'li-carousel'));
check('2026-12-09 and 2026-12-23 have li-carousel (fortnightly)', has('2026-12-09', 'li-carousel') && has('2026-12-23', 'li-carousel'));
check('2026-12-10 has no LinkedIn slot; 2026-12-03 has one', !has('2026-12-10', 'li') && has('2026-12-03', 'li'));
check('Wednesday trial reel is optional', slots.some((s) => s.kind === 'trial' && (s.state === 'optional' || s.baseState === 'optional')), JSON.stringify(slots.filter((s) => s.kind === 'trial').slice(0, 2)));
check('Friday company-page reshare is derived', on('2026-11-13').some((s) => s.kind === 'reshare' && s.state === 'derived'));
check('2nd Wednesday note on 2026-12-09, none in March 2027', has('2026-12-09', 'note') && !slots.some((s) => s.kind === 'note' && s.date.startsWith('2027-03')));
check('yt-long is fortnightly on Mondays at 11:00 from 16 November 2026', has('2026-11-16', 'yt-long', 'yt') && has('2026-11-30', 'yt-long', 'yt') && has('2026-12-14', 'yt-long', 'yt') && has('2027-01-11', 'yt-long', 'yt') && !has('2026-11-09', 'yt-long') && !has('2026-11-23', 'yt-long') && on('2026-11-16').find((s) => s.kind === 'yt-long')?.time === '11:00', JSON.stringify(slots.filter((s) => s.kind === 'yt-long').map((s) => s.date)));
check('no yt-long slot is generated by a third-Monday rule any more', !slots.some((s) => s.kind === 'yt-long' && s.generated && !['2026-11-16', '2026-11-30', '2026-12-14', '2026-12-28', '2027-01-11', '2027-01-25', '2027-02-08', '2027-02-22', '2027-03-08', '2027-03-22'].includes(s.date) && !s.pieceId), JSON.stringify(slots.filter((s) => s.kind === 'yt-long').map((s) => s.date + (s.pieceId ? '*' : ''))));
check('no ordinary slot on any dark-map day (the scheduled long-video upload excepted)', ['2026-11-07', '2026-11-10', '2026-11-11', '2026-11-15', '2026-11-21', '2026-12-31', '2027-02-01'].every((d) => !on(d).some((s) => !['greeting', 'yt-long'].includes(s.kind))));
check('the long video is generated on a dark day as a scheduled upload (22 March 2027, Holi)', has('2027-03-22', 'yt-long', 'yt') && on('2027-03-22').find((s) => s.kind === 'yt-long')?.scheduledUpload === true && cal.data.days['2027-03-22']?.rule === 'dark', JSON.stringify(cal.data.days['2027-03-22']));
{
  const apr = (await call('GET', '/api/calendar?from=2027-04-01&to=2027-04-30')).data.slots.filter((s) => s.kind === 'yt-long');
  check('the VSP film sits on Monday 5 April 2027 at 11:00, the fortnight after the series', apr.some((s) => s.date === '2027-04-05' && s.pieceId === 'film' && s.time === '11:00'), JSON.stringify(apr));
  const regApr = await call('POST', '/api/slots/regenerate', { from: '2027-04-01', to: '2027-04-30' });
  const apr2 = (await call('GET', '/api/calendar?from=2027-04-01&to=2027-04-30')).data.slots.filter((s) => s.kind === 'yt-long' && s.date === '2027-04-05');
  check('regenerating April keeps one long-video slot on 5 April (the hand-made one is matched)', regApr.status === 200 && apr2.length === 1 && apr2[0].pieceId === 'film', JSON.stringify(apr2));
}
check('quiet windows are markers', cal.data.days['2026-12-17']?.quiet === true && cal.data.days['2026-12-17']?.rule === 'normal' && on('2026-12-17').length > 0);
check('days report the dark rule', cal.data.days['2026-11-09']?.rule === 'dark');

// Pieces made for the test; removed at the end.
const made = [];
const mk = async (type, hook) => {
  const r = await call('POST', '/api/pieces', { type, pillar: 'problem', status: 'draft', hook, targets: ['vd-ig'] });
  made.push(r.data.id);
  return r.data;
};
const carousel = await mk('carousel', 'Calendar test carousel');
const reel = await mk('reel-animated', 'Calendar test reel');
// The November plan fills the early slots, so the test uses the first two open Monday reel slots.
const openReels = slots.filter((s) => s.kind === 'reel' && s.state === 'open' && s.accountId === 'vd-ig').sort((a, b) => a.date.localeCompare(b.date));
const reelSlot = openReels[0];
const otherReel = openReels.find((s) => s.date > reelSlot.date);
const carouselSlot = slots.find((s) => s.kind === 'carousel');
check('test fixtures exist', Boolean(carousel.id && reel.id && reelSlot && otherReel && carouselSlot));

const bad = await call('POST', `/api/pieces/${carousel.id}/place`, { slotId: reelSlot.id });
check('placing a carousel piece into a reel slot is refused (422 with a reason)', bad.status === 422 && /carousel/i.test(bad.data.error || ''), JSON.stringify(bad.data));

const manual = await call('POST', '/api/slots', { date: '2026-11-09', time: '19:30', accountId: 'vd-ig', kind: 'reel', state: 'open', baseState: 'open', source: 'manual', generated: false });
const darkTry = await call('POST', `/api/pieces/${reel.id}/place`, { slotId: manual.data.id });
check('placing into a dark day is refused (422 with the reason)', darkTry.status === 422 && /dark/i.test(darkTry.data.error || ''), JSON.stringify(darkTry.data));
await call('DELETE', `/api/slots/${manual.data.id}`);
const byDate = await call('POST', `/api/pieces/${reel.id}/place`, { date: '2026-11-10', create: true });
check('placing by date onto a dark day is refused', byDate.status === 422 && /dark/i.test(byDate.data.error || ''), JSON.stringify(byDate.data));

const ok = await call('POST', `/api/pieces/${reel.id}/place`, { slotId: reelSlot.id });
check('placing a reel into a reel slot works and fills the slot', ok.status === 200 && ok.data.slot.state === 'filled' && ok.data.slot.pieceId === reel.id, JSON.stringify(ok.data).slice(0, 300));
const pc = await call('GET', `/api/pieces/${reel.id}`);
check('the piece takes the slot\'s date', pc.data.plannedDate === reelSlot.date, JSON.stringify(pc.data.plannedDate));

const occupied = await call('POST', `/api/pieces/${(await mk('reel-animated', 'Calendar test reel two')).id}/place`, { slotId: reelSlot.id });
check('a filled slot refuses a second piece (409)', occupied.status === 409, JSON.stringify(occupied.data));

const regen3 = await call('POST', '/api/slots/regenerate', { from, to });
const still = (await call('GET', `/api/calendar?from=${reelSlot.date}&to=${reelSlot.date}`)).data.slots.find((s) => s.id === reelSlot.id);
check('regeneration keeps the filled slot', regen3.status === 200 && still?.pieceId === reel.id);

const moved = await call('POST', `/api/pieces/${reel.id}/place`, { date: otherReel.date, fromSlotId: reelSlot.id });
check('moving to another Monday takes that day\'s reel slot and frees the old one', moved.status === 200 && moved.data.slot.date === otherReel.date && moved.data.slot.kind === 'reel', JSON.stringify(moved.data).slice(0, 300));
const freed = (await call('GET', `/api/calendar?from=${reelSlot.date}&to=${reelSlot.date}`)).data.slots.find((s) => s.id === reelSlot.id);
check('the old slot is open again', freed?.state === 'open' && !freed.pieceId);
const un = await call('POST', `/api/pieces/${reel.id}/unplace`, {});
check('unplace empties the slot and clears plannedDate', un.status === 200 && !un.data.piece.plannedDate);

const today = await call('GET', '/api/today?date=2026-11-02');
check('Today carries openSlots with what is missing', Array.isArray(today.data.openSlots) && today.data.openSlots.length > 0 && today.data.openSlots.every((s) => Array.isArray(s.missing)), JSON.stringify(today.data.openSlots?.[0]));

const noFile = await call('POST', '/api/calendar/import-rows', {});
if (!process.env.ROUNDTRIP) check('import-rows answers with a clear message (with or without data/import-calendar.json)', noFile.status === 200 && typeof noFile.data.message === 'string' && (noFile.data.ok === false ? /import-calendar/.test(noFile.data.message) : noFile.data.imported > 0), JSON.stringify(noFile.data));

for (const id of made) await call('DELETE', `/api/pieces/${id}`);

// ---- optional: CSV round trip against a scratch copy of Studio
if (process.env.ROUNDTRIP) {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const csvFile = process.env.CSV || path.resolve(here, '../../Marketing/POSTING/calendar.csv');
  const original = fs.readFileSync(csvFile, 'utf8');
  const parse = (s) => {
    const rows = []; let row = []; let f = ''; let q = false;
    for (let i = 0; i < s.length; i += 1) {
      const c = s[i];
      if (q) { if (c === '"' && s[i + 1] === '"') { f += '"'; i += 1; } else if (c === '"') q = false; else f += c; }
      else if (c === '"') q = true; else if (c === ',') { row.push(f); f = ''; }
      else if (c === '\n') { row.push(f); rows.push(row); row = []; f = ''; } else if (c !== '\r') f += c;
    }
    if (f || row.length) { row.push(f); rows.push(row); }
    const [h, ...body] = rows; return body.filter((r) => r.length > 1).map((r) => Object.fromEntries(h.map((k, i) => [k, r[i] || ''])));
  };
  const rows = parse(original);
  const full = rows.map((r) => ({
    date: r.Date, time: r['Time (IST)'], channel: r.Channel, format: r.Format, id: r.Id, hook: r.Hook, notes: r.Notes, status: r.Status,
    week: r.Week, day: r.Day, face: r['Your face'], ready: r['Ready?'], caption: r['Caption or text (when not in a source file)'],
    postedLink: r['Posted link'], realReplies: r['Real replies'], callsBooked: r['Calls booked'],
  }));
  const minimal = full.map(({ date, time, channel, format, id, hook, notes, status }) => ({ date, time, channel, format, id, hook, notes, status }));
  const importFile = path.join(process.env.ROUNDTRIP, 'import-calendar.json');

  for (const [label, payload] of [['full rows', full], ['the eight listed fields only', minimal]]) {
    fs.writeFileSync(importFile, JSON.stringify(payload, null, 2));
    const imp = await call('POST', '/api/calendar/import-rows', {});
    check(`import (${label}) succeeds: ${imp.data.message}`, imp.status === 200 && imp.data.ok === true && imp.data.imported === rows.length, JSON.stringify(imp.data));
    const imp2 = await call('POST', '/api/calendar/import-rows', {});
    check(`import (${label}) is idempotent`, imp2.data.created === 0 && imp2.data.filled === 0, JSON.stringify(imp2.data));
    const exp = await call('POST', '/api/calendar/export-csv', { dryRun: true });
    const got = exp.data.csv || '';
    if (label === 'full rows') {
      check('export reproduces calendar.csv byte for byte', got === original, `rows ${exp.data.rows} vs ${rows.length}`);
    } else {
      // Columns the eight fields cannot carry (Week, Day, Your face, Ready?, Caption, Posted link...) may differ; the rest must match.
      const a = parse(got); const keep = ['Date', 'Time (IST)', 'Channel', 'Format', 'Id', 'Hook', 'Notes', 'Status'];
      const same = a.length === rows.length && a.every((r, i) => keep.every((k) => r[k] === rows[i][k]));
      check('export reproduces the eight imported columns for every row', same, `rows ${a.length} vs ${rows.length}`);
    }
    // Reset the slots between the two passes.
    for (const s of (await call('GET', `/api/calendar?from=2026-10-01&to=2027-04-30`)).data.slots) {
      if (s.csv) await call('DELETE', `/api/slots/${s.id}`);
    }
    await call('POST', '/api/slots/regenerate', { from, to });
  }
  fs.rmSync(importFile, { force: true });
}

console.log(`\n${passed} passed, ${failed} failed`);
if (scratch) await scratch.stop();
process.exit(failed ? 1 : 0);
